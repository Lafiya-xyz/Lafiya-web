#!/usr/bin/env node
/**
 * Alert-quality report (issue #948).
 *
 * Reads alert outcomes for a month, computes actionable vs. noise outcomes,
 * time-to-ack, and per-alert frequency, then:
 *   - writes a monthly markdown report (default: reports/alerts/<YYYY-MM>.md);
 *   - with --create-issues, opens one review issue per alert that exceeds the
 *     noise budget (skipped when an open issue with the same title exists).
 *
 * Usage:
 *   node scripts/alert-quality.mjs --input <path> [--month YYYY-MM]
 *                                  [--out <path>] [--create-issues] [--strict]
 *
 * Input JSON schema (--input):
 * {
 *   "month": "2026-10",
 *   "alerts": [
 *     {
 *       "id": "public_card_availability",
 *       "pages": 4,
 *       "outcomes": [
 *         { "outcome": "actionable", "ackedAt": "2026-10-02T10:05:00Z", "firedAt": "2026-10-02T10:00:00Z" },
 *         { "outcome": "noise", "ackedAt": "2026-10-03T10:20:00Z", "firedAt": "2026-10-03T10:00:00Z" }
 *       ]
 *     }
 *   ]
 * }
 *
 * Only alert IDs, outcome classes, and timings are read — never patient data.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const ROOT = process.cwd();
const CATALOG_PATH = join(ROOT, "ops/alerts/catalog.json");
const OUTCOMES = new Set(["actionable", "noise"]);

const args = process.argv.slice(2);
function argValue(name, fallback) {
  const index = args.indexOf(name);
  return index >= 0 && args[index + 1] ? args[index + 1] : fallback;
}

export function loadNoiseBudget(catalog) {
  const budget = catalog?.noiseBudget ?? {};
  return {
    maxNoiseRatio: budget.maxNoiseRatio ?? 0.3,
    maxPagesPerMonth: budget.maxPagesPerMonth ?? 20,
    maxTimeToAckMinutes: budget.maxTimeToAckMinutes ?? 15,
  };
}

function minutesBetween(firedAt, ackedAt) {
  const fired = Date.parse(firedAt);
  const acked = Date.parse(ackedAt);
  if (Number.isNaN(fired) || Number.isNaN(acked) || acked < fired) return null;
  return (acked - fired) / 60000;
}

export function summarizeAlert(alert, budget) {
  const outcomes = Array.isArray(alert.outcomes) ? alert.outcomes : [];
  const actionable = outcomes.filter((o) => o.outcome === "actionable").length;
  const noise = outcomes.filter((o) => o.outcome === "noise").length;
  const unknown = outcomes.length - actionable - noise;
  const ackTimes = outcomes
    .map((o) => minutesBetween(o.firedAt, o.ackedAt))
    .filter((m) => m !== null);
  const avgTimeToAckMinutes = ackTimes.length
    ? Math.round((ackTimes.reduce((a, b) => a + b, 0) / ackTimes.length) * 10) / 10
    : null;
  const pages = Number.isFinite(alert.pages) ? alert.pages : outcomes.length;
  const noiseRatio = outcomes.length ? noise / outcomes.length : 0;

  const reasons = [];
  if (noiseRatio > budget.maxNoiseRatio) {
    reasons.push(
      `noise ratio ${(noiseRatio * 100).toFixed(0)}% exceeds ${(budget.maxNoiseRatio * 100).toFixed(0)}%`,
    );
  }
  if (pages > budget.maxPagesPerMonth) {
    reasons.push(`pages ${pages} exceed ${budget.maxPagesPerMonth}/month`);
  }
  if (avgTimeToAckMinutes !== null && avgTimeToAckMinutes > budget.maxTimeToAckMinutes) {
    reasons.push(
      `time-to-ack ${avgTimeToAckMinutes}m exceeds ${budget.maxTimeToAckMinutes}m`,
    );
  }

  return {
    id: alert.id,
    pages,
    actionable,
    noise,
    unknown,
    noiseRatio: Math.round(noiseRatio * 1000) / 1000,
    avgTimeToAckMinutes,
    exceedsBudget: reasons.length > 0,
    reasons,
  };
}

export function buildReport(input, catalog, { month } = {}) {
  const budget = loadNoiseBudget(catalog);
  const reportMonth = month ?? input.month ?? new Date().toISOString().slice(0, 7);
  const alerts = (Array.isArray(input.alerts) ? input.alerts : []).map((alert) =>
    summarizeAlert(alert, budget),
  );
  const totalPages = alerts.reduce((sum, a) => sum + a.pages, 0);
  const totalNoise = alerts.reduce((sum, a) => sum + a.noise, 0);
  const totalOutcomes = alerts.reduce(
    (sum, a) => sum + a.actionable + a.noise + a.unknown,
    0,
  );
  const overallNoiseRatio = totalOutcomes ? totalNoise / totalOutcomes : 0;
  const overBudget = alerts.filter((a) => a.exceedsBudget);

  const lines = [
    `# Alert quality report — ${reportMonth}`,
    "",
    `Generated by \`scripts/alert-quality.mjs\` (issue #948).`,
    "",
    "## Summary",
    "",
    `- Alerts tracked: **${alerts.length}**`,
    `- Pages fired: **${totalPages}** (budget ${budget.maxPagesPerMonth}/month)`,
    `- Overall noise ratio: **${(overallNoiseRatio * 100).toFixed(0)}%** (budget ${(budget.maxNoiseRatio * 100).toFixed(0)}%)`,
    `- Alerts over noise budget: **${overBudget.length}**`,
    "",
    "## Per-alert quality",
    "",
    "| Alert | Pages | Actionable | Noise | Noise ratio | Avg time-to-ack | Over budget |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...alerts.map(
      (a) =>
        `| \`${a.id}\` | ${a.pages} | ${a.actionable} | ${a.noise} | ${(a.noiseRatio * 100).toFixed(0)}% | ${
          a.avgTimeToAckMinutes === null ? "n/a" : `${a.avgTimeToAckMinutes}m`
        } | ${a.exceedsBudget ? "yes" : "no"} |`,
    ),
    "",
    "## Review required",
    "",
    ...(overBudget.length
      ? overBudget.map((a) => `- \`${a.id}\`: ${a.reasons.join("; ")}`)
      : ["- none"]),
    "",
    "See [alert quality and noise budget](../operations/alert-quality.md) for the",
    "review procedure.",
    "",
  ];
  return { month: reportMonth, budget, alerts, overBudget, markdown: lines.join("\n") };
}

function createIssue(alert, month) {
  const title = `Alert noise review: ${alert.id} (${month})`;
  const existing = execFileSync(
    "gh",
    [
      "issue",
      "list",
      "--state",
      "open",
      "--search",
      `"${title}" in:title`,
      "--json",
      "number",
    ],
    { encoding: "utf8" },
  );
  if (JSON.parse(existing).length > 0) return;
  const body = [
    `The alert \`${alert.id}\` exceeded its noise budget in ${month}.`,
    "",
    `- Pages: ${alert.pages}`,
    `- Actionable: ${alert.actionable}`,
    `- Noise: ${alert.noise}`,
    `- Noise ratio: ${(alert.noiseRatio * 100).toFixed(0)}%`,
    `- Average time-to-ack: ${alert.avgTimeToAckMinutes ?? "n/a"}m`,
    "",
    "Reasons:",
    ...alert.reasons.map((r) => `- ${r}`),
    "",
    "See docs/operations/alert-quality.md for the review procedure.",
  ].join("\n");
  execFileSync("gh", ["issue", "create", "--title", title, "--body", body], {
    stdio: "inherit",
  });
}

function main() {
  const inputPath = argValue("--input");
  if (!inputPath) {
    console.error("Usage: node scripts/alert-quality.mjs --input <path> [--month YYYY-MM]");
    process.exit(1);
  }
  const input = JSON.parse(readFileSync(join(ROOT, inputPath), "utf8"));
  const catalog = JSON.parse(readFileSync(CATALOG_PATH, "utf8"));
  const report = buildReport(input, catalog, { month: argValue("--month") });

  const outPath = argValue("--out", join("reports/alerts", `${report.month}.md`));
  mkdirSync(dirname(join(ROOT, outPath)), { recursive: true });
  writeFileSync(join(ROOT, outPath), report.markdown);
  console.log(`Wrote ${outPath}`);

  for (const alert of report.overBudget) {
    console.log(`::warning::Alert "${alert.id}" exceeds noise budget: ${alert.reasons.join("; ")}`);
    if (args.includes("--create-issues")) createIssue(alert, report.month);
  }
  if (args.includes("--strict") && report.overBudget.length > 0) process.exit(1);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
