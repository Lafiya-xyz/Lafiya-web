#!/usr/bin/env node
/**
 * Environment variable drift check (issue #789).
 *
 * Derives the canonical variable list from the Zod schemas in
 * lib/runtime-config.ts (server) and lib/env.ts (client) and:
 *   --write-doc   regenerates the table in docs/environment-variables.md
 *   --check-doc   fails when the generated table is out of date
 *   (always)      fails when a secret-named variable has a NEXT_PUBLIC_ prefix
 *   --platform    when VERCEL_TOKEN/VERCEL_PROJECT_ID are set, fetches the
 *                 variable *names* (never values) per Vercel target and
 *                 reports missing, extra and misclassified entries
 *   --report=FILE writes the Markdown report to FILE (for PR comments)
 */
import { readFileSync, writeFileSync } from "node:fs";

const DOC = "docs/environment-variables.md";
const START =
  "<!-- env-table:start (generated by scripts/env-drift.mjs; do not edit) -->";
const END = "<!-- env-table:end -->";
const TARGETS = ["preview", "production"];
const SECRET_PATTERN =
  /(SECRET|SERVICE_ROLE|PRIVATE|PASSWORD|TOKEN|SIGNING_KEY|API_KEY|HMAC|DATABASE_URL|DIRECT_URL)/;
// Platform-managed variables that are not part of the app schema.
const PLATFORM_ALLOW =
  /^(VERCEL|NEXT_PUBLIC_VERCEL|NODE_ENV|NEXT_PUBLIC_ENVIRONMENT|TURBO)/;

const args = process.argv.slice(2);
const has = (flag) => args.includes(flag);
const reportPath = args.find((a) => a.startsWith("--report="))?.slice(9);

export function parseSchema(source, marker) {
  const block = source.split(marker)[1]?.split("\n});")[0] ?? "";
  const entries = new Map();
  let current = null;
  for (const line of block.split("\n")) {
    const m = line.match(/^ {2}([A-Z0-9_]+):\s*(.*)$/);
    if (m) {
      current = m[1];
      entries.set(current, m[2]);
    } else if (current && !line.trim().startsWith("//")) {
      entries.set(current, entries.get(current) + line.trim());
    }
  }
  return entries;
}

export function classify(name) {
  return SECRET_PATTERN.test(name) ? "secret" : "public";
}

export function canonicalList() {
  const server = parseSchema(
    readFileSync("lib/runtime-config.ts", "utf8"),
    "const rawServerEnvSchema = z.object({",
  );
  const client = parseSchema(
    readFileSync("lib/env.ts", "utf8"),
    "export const clientEnvSchema = z.object({",
  );
  const all = new Map([...server, ...client]);
  return [...all]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, rule]) => ({
      name,
      required: !/optional|default\(/i.test(rule),
      exposure: name.startsWith("NEXT_PUBLIC_") ? "browser" : "server",
      classification: classify(name),
      rule: rule.replace(/,$/, "").replace(/\|/g, "\\|"),
    }));
}

export function publicSecretViolations(names) {
  return names.filter(
    (n) => n.startsWith("NEXT_PUBLIC_") && classify(n) === "secret",
  );
}

function renderTable(list) {
  const rows = list.map(
    (v) =>
      `| \`${v.name}\` | ${v.required ? "**Required**" : "Optional"} | ${v.exposure} | ${v.classification} | \`${v.rule}\` |`,
  );
  return [
    START,
    "",
    "| Variable | Required | Exposure | Classification | Validation rule |",
    "|---|---|---|---|---|",
    ...rows,
    "",
    END,
  ].join("\n");
}

function syncDoc(list, write) {
  const doc = readFileSync(DOC, "utf8");
  const table = renderTable(list);
  const pattern = new RegExp(
    `${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`,
  );
  const next = pattern.test(doc)
    ? doc.replace(pattern, table)
    : doc.replace(
        "\n---\n",
        `\n## Canonical variable list\n\n${table}\n\n---\n`,
      );
  if (next === doc) return true;
  if (write) writeFileSync(DOC, next);
  return write;
}

async function platformNames() {
  const { VERCEL_TOKEN, VERCEL_PROJECT_ID, VERCEL_TEAM_ID } = process.env;
  if (!VERCEL_TOKEN || !VERCEL_PROJECT_ID) return null;
  const team = VERCEL_TEAM_ID ? `?teamId=${VERCEL_TEAM_ID}` : "";
  const res = await fetch(
    `https://api.vercel.com/v9/projects/${VERCEL_PROJECT_ID}/env${team}`,
    {
      headers: { Authorization: `Bearer ${VERCEL_TOKEN}` },
    },
  );
  if (!res.ok) throw new Error(`Vercel API returned ${res.status}`);
  const { envs } = await res.json();
  const byTarget = Object.fromEntries(TARGETS.map((t) => [t, new Set()]));
  for (const env of envs ?? []) {
    for (const t of env.target ?? []) byTarget[t]?.add(env.key);
  }
  return byTarget;
}

async function main() {
  const list = canonicalList();
  const lines = ["## Environment variable drift report", ""];
  let failed = false;

  const schemaViolations = publicSecretViolations(list.map((v) => v.name));
  for (const name of schemaViolations)
    lines.push(
      `- :x: \`${name}\` looks secret but has a public \`NEXT_PUBLIC_\` prefix`,
    );
  failed ||= schemaViolations.length > 0;

  if (has("--write-doc")) syncDoc(list, true);
  if (has("--check-doc") && !syncDoc(list, false)) {
    lines.push(
      `- :x: ${DOC} is out of date; run \`node scripts/env-drift.mjs --write-doc\``,
    );
    failed = true;
  }

  if (has("--platform")) {
    const platform = await platformNames();
    if (!platform) {
      lines.push(
        "- Platform diff skipped (VERCEL_TOKEN / VERCEL_PROJECT_ID not set)",
      );
    } else {
      const schema = new Set(list.map((v) => v.name));
      for (const target of TARGETS) {
        const names = platform[target];
        const missing = list
          .filter((v) => v.required && !names.has(v.name))
          .map((v) => v.name);
        const extra = [...names].filter(
          (n) => !schema.has(n) && !PLATFORM_ALLOW.test(n),
        );
        const misclassified = publicSecretViolations([...names]);
        lines.push(`### ${target}`, "");
        lines.push(
          `- Missing required: ${missing.map((n) => `\`${n}\``).join(", ") || "none"}`,
        );
        lines.push(
          `- Not in schema: ${extra.map((n) => `\`${n}\``).join(", ") || "none"}`,
        );
        lines.push(
          `- Secret with public prefix: ${misclassified.map((n) => `\`${n}\``).join(", ") || "none"}`,
          "",
        );
        failed ||= missing.length > 0 || misclassified.length > 0;
      }
    }
  }

  if (lines.length === 2) lines.push("No drift detected.");
  const report = lines.join("\n");
  console.log(report);
  if (reportPath) writeFileSync(reportPath, `${report}\n`);
  if (failed) process.exit(1);
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
